"""
Planner Schemas — Milestone 10

This module defines the strongly-typed ExecutionPlan and all its supporting
models. The ExecutionPlan is the ONLY output of the Planner. It is NEVER
generated by the Executor or any other component.

Design Contract:
    - The Planner produces an ExecutionPlan.
    - The Plan Validator (Pydantic) validates it before Executor receives it.
    - The Executor may correct obvious tool mismatches before execution
      (e.g. DOCUMENT_SUMMARY planned with search → swap to reader).
    - Future tools (Gmail, GitHub, etc.) can be added to ToolEnum without
      changing any Executor logic.
"""

from __future__ import annotations

import uuid
from enum import Enum
from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------

class TaskType(str, Enum):
    """Top-level classification of what the user wants to accomplish."""

    DOCUMENT_SUMMARY = "DOCUMENT_SUMMARY"
    """Summarise an entire attached document."""

    DOCUMENT_QA = "DOCUMENT_QA"
    """Answer a factual question from attached documents (semantic retrieval)."""

    DOCUMENT_COMPARISON = "DOCUMENT_COMPARISON"
    """Compare or contrast two or more attached documents."""

    DOCUMENT_SEARCH = "DOCUMENT_SEARCH"
    """Search documents for a concept, term, or entity."""

    DOCUMENT_EXTRACTION = "DOCUMENT_EXTRACTION"
    """Extract structured data (tables, lists, fields) from documents."""

    DOCUMENT_TRANSLATION = "DOCUMENT_TRANSLATION"
    """Translate document content into a different language."""

    DOCUMENT_REWRITE = "DOCUMENT_REWRITE"
    """Improve, rephrase, or reformat document content."""

    GENERAL = "GENERAL"
    """Answer using general LLM knowledge without documents."""

    HYBRID = "HYBRID"
    """Combine document knowledge with general LLM expertise."""

    CONVERSATION_MEMORY = "CONVERSATION_MEMORY"
    """Query refers to earlier parts of the conversation."""

    UNKNOWN = "UNKNOWN"
    """Fallback when the planner cannot determine intent."""


class ToolName(str, Enum):
    """
    Canonical names for all registered tools.

    Future tools (Gmail, GitHub, Calendar…) are added here only.
    The Executor and Tool Registry are designed so that adding a new
    ToolName requires ZERO changes to Executor logic.
    """

    DOCUMENT_READER = "document_reader"
    """Load and read the full text of one or more attached documents."""

    DOCUMENT_SEARCH = "document_search"
    """Semantically search attached documents via embeddings + Qdrant."""

    GENERAL_LLM = "general_llm"
    """Invoke the LLM directly without any document context."""

    CONVERSATION_MEMORY = "conversation_memory"
    """Retrieve recent conversation history from the database."""

    # -----------------------------------------------------------------------
    # Future tools (not yet implemented but registered here for planning)
    # -----------------------------------------------------------------------
    # GMAIL = "gmail"
    # GOOGLE_DRIVE = "google_drive"
    # GITHUB = "github"
    # CALENDAR = "calendar"
    # WEB_SEARCH = "web_search"
    # PYTHON_EXECUTOR = "python_executor"
